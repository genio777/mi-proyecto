import {readFile,writeFile} from 'node:fs/promises';
const file='public/data/chargers-spain.json';
const source='data/verified-station-prices.json';
const catalog=JSON.parse(await readFile(file,'utf8'));
const overlay=JSON.parse(await readFile(source,'utf8'));
if(!Array.isArray(catalog.chargers)||!Array.isArray(overlay.prices))throw Error('Invalid price input');
const byId=new Map(catalog.chargers.map(c=>[String(c.id),c]));
const seen=new Set();
let applied=0,missing=0;
for(const row of overlay.prices){
 if(!row||typeof row.id!=='string'||seen.has(row.id))throw Error('Duplicate or invalid tariff id');
 seen.add(row.id);
 if(typeof row.sourceUrl!=='string'||!/^https:\/\//.test(row.sourceUrl)||!Number.isFinite(Date.parse(row.checkedAt)))throw Error('Unverified tariff: '+row.id);
 if(typeof row.price!=='number'||!Number.isFinite(row.price)||row.price<0||row.unit!=='EUR/kWh')throw Error('Invalid price/unit: '+row.id);
 if(row.hasExtraFees!==false)throw Error('Additional fees or uncertain total price: '+row.id);
 if(row.taxIncluded!==true)throw Error('Final customer price must include taxes: '+row.id);
 if(row.priceBasis!=='ad_hoc')throw Error('Price must be public pay-as-you-go tariff: '+row.id);
 if(!Array.isArray(row.tariffElements)||row.tariffElements.length!==1)throw Error('Connector tariff must contain exactly one unconditional energy element: '+row.id);
 const element=row.tariffElements[0];
 if(element.type!=='ENERGY'||element.price!==row.price||element.currency!=='EUR'||element.restrictions!=null)throw Error('Conditional or multi-component tariff cannot be reduced to EUR/kWh: '+row.id);
 if(row.tariffElements.some(e=>e.type!=='ENERGY'))throw Error('Non-energy fees found: '+row.id);
 if(row.price===0&&(row.requiresPurchase!==false||row.timeLimitMinutes!==null||row.membershipRequired!==false||row.publicAccess!==true))throw Error('Conditional free tariff cannot be used for unrestricted 0 EUR routes: '+row.id);
 if(typeof row.stationEvidence!=='string'||row.stationEvidence.trim().length<12)throw Error('Missing station-specific evidence: '+row.id);
 if(typeof row.conditions!=='string'||!row.conditions.trim())throw Error('Missing usage conditions: '+row.id);
 if(!Number.isFinite(row.lat)||!Number.isFinite(row.lng))throw Error('Missing station coordinates: '+row.id);
 if(typeof row.connectorId!=='string'||!row.connectorId.trim())throw Error('Missing official connector ID: '+row.id);
 if(typeof row.connectorType!=='string'||!row.connectorType.trim())throw Error('Missing connector type: '+row.id);
 if(!Number.isFinite(row.powerKw)||row.powerKw<=0)throw Error('Missing connector power: '+row.id);
 const age=Date.now()-Date.parse(row.checkedAt);
 if(age<0||age>7*86400000)throw Error('Tariff expired (7 days): '+row.id);
 const station=byId.get(row.id);
 if(!station){missing++;continue}
 const distance=Math.hypot((station.lat-row.lat)*111000,(station.lng-row.lng)*111000*Math.cos(station.lat*Math.PI/180));
 if(distance>100)throw Error('Tariff coordinates do not match catalog station: '+row.id);
 if(String(station.connector||'').toLowerCase().indexOf(row.connectorType.toLowerCase())===-1)throw Error('Connector type mismatch: '+row.id);
 if(Math.abs(Number(station.power)-row.powerKw)>1)throw Error('Connector power mismatch: '+row.id);
 if(!row.stationEvidence.includes(row.connectorId))throw Error('Official connector ID not present in station evidence: '+row.id);
 const connectors=Array.isArray(station.connectors)?station.connectors:[];
 const matching=connectors.filter(c=>c.officialConnectorId===row.connectorId&&c.type.toLowerCase()===row.connectorType.toLowerCase()&&Math.abs(c.powerKw-row.powerKw)<=1);
 if(matching.length!==1)throw Error('No unique official connector identity in national catalog: '+row.id);
 if(connectors.length!==1)throw Error('Multi-connector station cannot receive a station-wide price: '+row.id);
 if(!/^https:\/\//.test(row.sourceUrl))throw Error('Invalid source URL: '+row.id);
 matching[0].price=row.price;
 station.price=row.price;
 station.priceSource=row.sourceUrl;
 station.priceVerifiedAt=row.checkedAt;
 station.priceConditions=row.conditions;
 applied++;
}
if(missing)throw Error('Tariff station IDs absent from current catalog: '+missing);
await writeFile(file,JSON.stringify(catalog));
console.log('Station-specific verified prices applied:',applied,'unknown:',catalog.chargers.filter(c=>c.price===null).length);
